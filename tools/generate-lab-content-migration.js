'use strict';

const fs = require('node:fs');
const path = require('node:path');
const bottleImporter = require('./bottle-lab-pro-import.js');
const labelImporter = require('./label-lab-pro-import.js');

const root = path.join(__dirname, '..');
const labelItems = labelImporter.loadItems(path.join(root, 'content-bank', 'label-lab-pro', 'bank'));
const bottlePlan = bottleImporter.buildImportPlan();
const labelPlan = labelImporter.buildImportPlan(labelItems);
const records = [...bottlePlan.records, ...labelPlan.records];
const excludedLabelIds = labelPlan.excluded.map((entry) => entry.item_id);

const quotedExcluded = excludedLabelIds.map((id) => `'${id.replaceAll("'", "''")}'`).join(', ');
const payload = JSON.stringify(records);
const sql = `-- Generated by tools/generate-lab-content-migration.js.
-- The reviewed banks/importers remain the source of truth; this snapshot makes their private
-- runtime projection reproducible without placing a service-role key on developer machines.
with payload as (
  select *
  from jsonb_to_recordset($epistemic_lab_content$${payload}$epistemic_lab_content$::jsonb) as x(
    item_id text,
    lab_type text,
    canonical_id text,
    is_active boolean,
    content_version text,
    evaluation_version text,
    public_content jsonb,
    evaluation_spec jsonb,
    reveal_content jsonb
  )
)
insert into public.lab_items (
  item_id, lab_type, canonical_id, is_active, content_version, evaluation_version,
  public_content, evaluation_spec, reveal_content
)
select
  item_id, lab_type, canonical_id, is_active, content_version, evaluation_version,
  public_content, evaluation_spec, reveal_content
from payload
on conflict (item_id) do update set
  lab_type = excluded.lab_type,
  canonical_id = excluded.canonical_id,
  is_active = excluded.is_active,
  content_version = excluded.content_version,
  evaluation_version = excluded.evaluation_version,
  public_content = excluded.public_content,
  evaluation_spec = excluded.evaluation_spec,
  reveal_content = excluded.reveal_content,
  updated_at = now();

update public.lab_items
set is_active = false, updated_at = now()
where lab_type = 'label'
  and is_active = true
  and item_id in (${quotedExcluded});
`;

const target = path.join(root, 'supabase', 'migrations', '20260816013000_refresh_investigation_lab_content.sql');
fs.writeFileSync(target, sql, 'utf8');
console.log(`Generated ${path.relative(root, target)}: ${records.length} active records, ${excludedLabelIds.length} excluded Label records.`);
